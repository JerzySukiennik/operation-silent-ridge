def land_dir():
    a = math.radians(LAND_HDG)
    return (math.cos(a), math.sin(a))


def land_point(s, lat=0.0):
    """Point on the landing area: s along the centreline from the ramp, lat to starboard (m)."""
    d = land_dir()
    n = (-d[1], d[0])    # starboard normal
    return (LAND_R0[0] + d[0] * s + n[0] * lat, LAND_R0[1] + d[1] * s + n[1] * lat)


def cat_dir(c):
    a = math.radians(c["hdg"])
    return (math.cos(a), math.sin(a))


def jbd(c):
    d = cat_dir(c)
    return (c["x"] - d[0] * JBD_GAP, c["y"] - d[1] * JBD_GAP)


def write_header(path):
    L = []
    w = L.append
    w("// Generated by UE_Test/scripts/carrier/layout.py - do not edit by hand. Carrier-local metres: X bow, Y starboard, Z up from the waterline.")
    w("#pragma once")
    w("")
    w('#include "CoreMinimal.h"')
    w("")
    w("namespace CarrierLayout")
    w("{")
    w(f"\tconstexpr double DeckZ = {DECK_Z};")
    w(f"\tconstexpr double HullTop = {HULL_TOP};")
    w(f"\tconstexpr double HangarFloor = {HANGAR_FLOOR};")
    w(f"\tconstexpr double HangarCeil = {HANGAR_CEIL};")
    w(f"\tconstexpr double SternX = {STERN_X};")
    w(f"\tconstexpr double BowX = {BOW_X};")
    w(f"\tconstexpr double HullHalfBeamTop = {HULL_HALF_BEAM_TOP};")
    w(f"\tinline const FVector2D Outline[] = {{{', '.join(f'FVector2D({x}, {y})' for x, y in OUTLINE)}}};")
    w("\tstruct FElevator { int32 Id; double X0, X1, Y0, Y1; bool bWorking; };")
    w(f"\tinline const FElevator Elevators[] = {{{', '.join('{%d, %s, %s, %s, %s, %s}' % (e['id'], e['x0'], e['x1'], e['y0'], e['y1'], 'true' if e.get('working') else 'false') for e in ELEVATORS)}}};")
    w(f"\tinline const FBox2D Island(FVector2D({ISLAND['x0']}, {ISLAND['y0']}), FVector2D({ISLAND['x1']}, {ISLAND['y1']}));")
    w(f"\tinline const FVector2D IslandDoor({ISLAND_DOOR[0]}, {ISLAND_DOOR[1]});")
    w(f"\tinline const FVector2D Spawn({SPAWN[0]}, {SPAWN[1]});")
    w(f"\tinline const FVector2D LandR0({LAND_R0[0]}, {LAND_R0[1]});")
    w(f"\tconstexpr double LandHdgDeg = {LAND_HDG};")
    w(f"\tconstexpr double LandWidth = {LAND_WIDTH};")
    w(f"\tconstexpr double LandLen = {LAND_LEN};")
    w(f"\tinline const double WiresS[] = {{{', '.join(str(s) for s in WIRES_S)}}};")
    w(f"\tconstexpr double WireHalf = {WIRE_HALF};")
    w(f"\tconstexpr double TouchdownS = {TOUCHDOWN_S};")
    w(f"\tconstexpr double GlideslopeDeg = {GLIDESLOPE_DEG};")
    w(f"\tinline const FVector Iflols({IFLOLS[0]}, {IFLOLS[1]}, {IFLOLS[2]});")
    w(f"\tinline const FVector2D LsoPlatform({LSO_PLATFORM[0]}, {LSO_PLATFORM[1]});")
    w("\tstruct FCat { int32 Id; double X, Y, HdgDeg, Stroke; };")
    w(f"\tinline const FCat Cats[] = {{{', '.join('{%d, %s, %s, %s, %s}' % (c['id'], c['x'], c['y'], c['hdg'], c['stroke']) for c in CATS)}}};")
    w(f"\tconstexpr double JbdGap = {JBD_GAP};")
    w(f"\tconstexpr double JbdLen = {JBD_LEN};")
    w(f"\tconstexpr double JbdWidth = {JBD_WIDTH};")
    w(f"\tinline const FVector PlayerJet({PLAYER_JET['x']}, {PLAYER_JET['y']}, {PLAYER_JET['hdg']});   // x, y, heading deg")
    w(f"\tinline const FVector ParkedJets[] = {{{', '.join(f'FVector({x}, {y}, {h})' for x, y, h in PARKED_JETS)}}};")
    w(f"\tinline const FBox2D Hangar(FVector2D({HANGAR['x0']}, {HANGAR['y0']}), FVector2D({HANGAR['x1']}, {HANGAR['y1']}));")
    w(f"\tconstexpr double TexX0 = {TEX_X0}, TexX1 = {TEX_X1}, TexY0 = {TEX_Y0}, TexY1 = {TEX_Y1};")
    w("}")
    open(path, "w").write("\n".join(L) + "\n")


